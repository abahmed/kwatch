package main

import (
	"bytes"
	"fmt"
	"sort"
)

const header = `// Code generated by cmd/upstreamreasons; DO NOT EDIT.
// Source: github.com/kubernetes/kubernetes at %s.
// Regenerate: make upstream-reasons (needs network; make upstream-check
// verifies this file against the tag).

package upstream
`

func quoteList(name, doc string, vals []string) []byte {
	var b bytes.Buffer
	fmt.Fprintf(&b, "\n%s\nvar %s = []string{\n", doc, name)
	for _, v := range vals {
		fmt.Fprintf(&b, "\t%q,\n", v)
	}
	b.WriteString("}\n")
	return b.Bytes()
}

// renderStates is the generated states file: the tag and the container
// and pod reason lists.
func renderStates(tag string, g map[string][]string) []byte {
	var b bytes.Buffer
	fmt.Fprintf(&b, header, tag)
	fmt.Fprintf(&b, "\n// Tag is the Kubernetes release the corpus was "+
		"generated from.\nconst Tag = %q\n", tag)
	b.Write(quoteList("WaitingReasons",
		"// WaitingReasons are the reasons of a container in the waiting "+
			"state.", g["waiting"]))
	b.Write(quoteList("KubeletTerminatedReasons",
		"// KubeletTerminatedReasons are the terminated reasons the\n"+
			"// kubelet writes or tests for.", g["terminated"]))
	b.Write(quoteList("PodReasons",
		"// PodReasons are the values of pod.status.reason.", g["pod"]))
	b.Write(quoteList("PodConditionReasons",
		"// PodConditionReasons are reasons on a pod condition.",
		g["podCondition"]))
	b.Write(quoteList("HPAConditionReasons",
		"// HPAConditionReasons are the reasons the HPA controller sets "+
			"on its\n// AbleToScale and ScalingActive conditions.",
		g["hpaCondition"]))
	return b.Bytes()
}

// renderEvents is the generated events file, Warning entries first.
func renderEvents(tag string, events map[string]bool) []byte {
	names := make([]string, 0, len(events))
	for r := range events {
		names = append(names, r)
	}
	sort.Strings(names)
	var b bytes.Buffer
	fmt.Fprintf(&b, header, tag)
	b.WriteString("\n// Events lists the event reasons the kubelet, the " +
		"scheduler and the\n// controller manager emit. Warning is " +
		"true when any call site records\n// the reason as a Warning." +
		"\nvar Events = []Event{\n")
	for _, r := range names {
		fmt.Fprintf(&b, "\t{%q, %t},\n", r, events[r])
	}
	b.WriteString("}\n")
	return b.Bytes()
}
